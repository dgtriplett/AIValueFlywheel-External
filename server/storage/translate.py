"""Translate the app's Postgres SQL into Databricks SQL for the Delta backend.

The app is written once, in Postgres dialect, against `db.fetch/execute`. On a
Lakebase install the SQL runs as-is. On a Delta install every statement passes
through `prepare()` (cached by SQL text) and the resulting `Prepared` plan is
executed by storage/delta.py with the call's arguments.

WHAT NEEDS MORE THAN A DIALECT SWAP
-----------------------------------
sqlglot handles the dialect itself (now(), DISTINCT ON, ->>, ILIKE, FILTER, …).
What Delta lacks is handled here, using server/storage/schema_meta.json (keys,
auto-id columns, foreign keys) generated from the Postgres schema:

  * `INSERT … ON CONFLICT`  -> MERGE INTO … USING (source) ON <conflict keys>
  * `RETURNING`             -> emulated: a read of the affected keys before/after
  * auto-increment ids      -> generated by the backend and injected into INSERTs
  * `ON DELETE CASCADE / SET NULL` -> emulated child DELETE / UPDATE first
  * `x = ANY(array)` / `x <> ALL(array)` -> array_contains
  * `jsonb_build_object` / `jsonb_agg` / `::jsonb` -> to_json / named_struct / STRING

Parameters ($1, $2, …) are bound by inlining them as SQL literals into the parsed
tree (sqlglot escapes them), never by string formatting.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from datetime import date, datetime
from decimal import Decimal
from functools import lru_cache
from pathlib import Path

import sqlglot
from sqlglot import exp

META_PATH = Path(__file__).with_name("schema_meta.json")
_PARAM = re.compile(r"(?<![:\w$])\$(\d+)")


class TranslationError(Exception):
    pass


@lru_cache(maxsize=1)
def schema_meta() -> dict:
    return json.loads(META_PATH.read_text())["tables"]


def table_meta(name: str) -> dict:
    meta = schema_meta().get(name)
    if meta is None:
        raise TranslationError(f"unknown table {name!r} (not in schema_meta.json)")
    return meta


# ---------------------------------------------------------------------------
# Parsing + dialect fixes
# ---------------------------------------------------------------------------
def _parse(sql: str) -> exp.Expression:
    text = _PARAM.sub(lambda m: f":p{m.group(1)}", sql.strip().rstrip(";"))
    try:
        trees = [t for t in sqlglot.parse(text, read="postgres") if t is not None]
    except sqlglot.errors.ParseError as exc:
        raise TranslationError(f"cannot parse SQL: {exc}") from exc
    if len(trees) != 1:
        raise TranslationError("expected exactly one statement")
    return trees[0]


def _fname(node: exp.Expression) -> str:
    if isinstance(node, exp.Anonymous):
        return node.name.lower()
    if isinstance(node, exp.Func):
        return node.sql_name().lower()
    return ""


def _fargs(node: exp.Expression) -> list[exp.Expression]:
    if isinstance(node, exp.Anonymous):
        return list(node.expressions)
    return [a for a in [node.this, *(node.args.get("expressions") or [])] if a is not None]


def _ordered_list(value: exp.Expression, order: exp.Order | None, distinct: bool,
                  where: exp.Expression | None = None) -> exp.Expression:
    """collect_list/collect_set of `value`, honoring an aggregate-level ORDER BY
    (which Databricks aggregates don't take) by sorting keyed structs. A FILTER
    clause stays on the aggregate itself."""
    def agg(fn: str, arg: exp.Expression) -> exp.Expression:
        call = exp.func(fn, arg)
        return exp.Filter(this=call, expression=where.copy()) if where is not None else call

    if order is None or not order.expressions:
        return agg("collect_set" if distinct else "collect_list", value)
    first = order.expressions[0]
    key = first.this if isinstance(first, exp.Ordered) else first
    keyed = agg("collect_list", exp.func("named_struct", exp.Literal.string("k"), key,
                                         exp.Literal.string("v"), value))
    sorted_ = exp.func("array_sort", keyed)
    if isinstance(first, exp.Ordered) and first.args.get("desc"):
        sorted_ = exp.func("reverse", sorted_)
    lam = exp.Lambda(this=exp.Dot(this=exp.column("e"), expression=exp.to_identifier("v")),
                     expressions=[exp.to_identifier("e")])
    return exp.func("transform", sorted_, lam)


def _split_agg_arg(arg: exp.Expression) -> tuple[exp.Expression, exp.Order | None, bool]:
    distinct = False
    order = None
    if isinstance(arg, exp.Order):
        order = arg
        arg = arg.this
    if isinstance(arg, exp.Distinct):
        distinct = True
        arg = arg.expressions[0]
    return arg, order, distinct


_NARROW_INTS = (exp.DataType.Type.INT, exp.DataType.Type.SMALLINT, exp.DataType.Type.TINYINT)


def _widen_int(dtype: exp.DataType) -> None:
    if dtype.this in _NARROW_INTS:
        dtype.set("this", exp.DataType.Type.BIGINT)
    for inner in dtype.expressions:
        if isinstance(inner, exp.DataType):
            _widen_int(inner)


def _pg_array_literal(text: str) -> exp.Expression:
    """'{a,b,"c d"}' -> ARRAY('a', 'b', 'c d')."""
    body = text.strip()
    if not (body.startswith("{") and body.endswith("}")):
        return exp.Literal.string(text)
    inner = body[1:-1].strip()
    if not inner:
        return exp.Array(expressions=[])
    import csv
    items = next(csv.reader([inner], skipinitialspace=True))
    return exp.Array(expressions=[exp.Literal.string(i) for i in items])


def _fix_dialect(tree: exp.Expression) -> exp.Expression:
    """Rewrite the Postgres-only constructs sqlglot leaves as-is for Databricks.

    Runs in passes because sqlglot's transform does not revisit the children of a
    node it has just replaced: scalar JSON builders are rewritten first, then the
    aggregates that wrap them.
    """

    def scalars(node: exp.Expression) -> exp.Expression:
        if isinstance(node, (exp.Cast, exp.TryCast)):
            # ::jsonb / ::json casts: JSON is stored as STRING in Delta.
            if node.to.this in (exp.DataType.Type.JSONB, exp.DataType.Type.JSON):
                return node.this
            # A Postgres array literal ('{}', '{a,b}') cast to an array type.
            if node.to.this == exp.DataType.Type.ARRAY and isinstance(node.this, exp.Literal) \
                    and node.this.is_string:
                return exp.cast(_pg_array_literal(node.this.this), node.to)
        # col = ANY(arr)  ->  array_contains(arr, col)
        if isinstance(node, exp.EQ) and isinstance(node.expression, exp.Any):
            return exp.func("array_contains", node.expression.this, node.this)
        # col <> ALL(arr)  ->  NOT array_contains(arr, col)
        if isinstance(node, exp.NEQ) and isinstance(node.expression, exp.All):
            return exp.not_(exp.func("array_contains", node.expression.this, node.this))
        name = _fname(node)
        if name in ("jsonb_build_object", "json_build_object"):
            # A struct; serialized to JSON text where it is used (see `serialize`).
            return exp.func("named_struct", *_fargs(node))
        if name == "jsonb_array_length":
            return exp.func("json_array_length", *_fargs(node))
        if name == "to_jsonb" and isinstance(node, exp.Anonymous):
            return exp.func("to_json", *_fargs(node))
        return node

    def aggregates(node: exp.Expression) -> exp.Expression:
        where = None
        if isinstance(node, exp.Filter) and (_fname(node.this) in ("jsonb_agg", "json_agg")
                                             or isinstance(node.this, exp.ArrayAgg)):
            where = node.expression if isinstance(node.expression, exp.Where) else exp.Where(this=node.expression)
            node = node.this
        name = _fname(node)
        if name in ("jsonb_agg", "json_agg"):
            value, order, distinct = _split_agg_arg(_fargs(node)[0])
            return exp.func("to_json", _ordered_list(value, order, distinct, where))
        if isinstance(node, exp.ArrayAgg):
            value, order, distinct = _split_agg_arg(node.this)
            return _ordered_list(value, order, distinct, where)
        return node

    tree = tree.transform(scalars)
    tree = tree.transform(aggregates)
    _aggregate_scalar_subqueries(tree)
    _expand_pk_group_by(tree)
    # Integer columns are BIGINT on Delta (generated ids exceed 32 bits), so ::int /
    # ::int[] casts must not narrow. A final pass, so casts inside rewritten nodes count.
    for cast in tree.find_all(exp.Cast, exp.TryCast):
        _widen_int(cast.to)
    # A bare jsonb_build_object (not aggregated) must still produce JSON text.
    for ns in list(tree.find_all(exp.Anonymous)):
        if ns.name.lower() == "named_struct" and not _inside_aggregate(ns):
            ns.replace(exp.func("to_json", ns.copy()))
    return tree


def _expand_pk_group_by(tree: exp.Expression) -> None:
    """Postgres lets `GROUP BY t.id` (a primary key) cover every other column of t
    (functional dependency); Databricks needs them listed. Expand such a GROUP BY to
    all of that table's columns."""
    tables = schema_meta()
    for sel in list(tree.find_all(exp.Select)):
        group = sel.args.get("group")
        if group is None:
            continue
        aliases: dict[str, str] = {}
        for t in sel.find_all(exp.Table):
            if t.find_ancestor(exp.Select) is sel and t.name in tables:
                aliases[t.alias_or_name] = t.name
        present = {(c.table, c.name) for c in group.expressions if isinstance(c, exp.Column)}
        extra = []
        for c in list(group.expressions):
            if not isinstance(c, exp.Column) or c.table not in aliases:
                continue
            meta = tables[aliases[c.table]]
            if meta["primary_key"] != [c.name]:
                continue
            for col in meta["columns"]:
                key = (c.table, col["name"])
                if key not in present:
                    present.add(key)
                    extra.append(exp.column(col["name"], c.table))
        if extra:
            group.set("expressions", list(group.expressions) + extra)


def _aggregate_scalar_subqueries(tree: exp.Expression) -> None:
    """Postgres allows a scalar subquery that returns one row; Databricks requires a
    correlated scalar subquery to be aggregated. Wrap the single projection in
    any_value(), or max_by/min_by when the subquery picks a row with ORDER BY … LIMIT 1."""
    for sub in list(tree.find_all(exp.Subquery)):
        parent = sub.parent
        if isinstance(parent, (exp.From, exp.Join, exp.Exists, exp.In, exp.Any, exp.All, exp.Lateral)) \
                or isinstance(sub.this, (exp.Union, exp.Except, exp.Intersect)):
            continue
        sel = sub.this
        if not isinstance(sel, exp.Select) or len(sel.expressions) != 1 or sel.args.get("group"):
            continue
        proj = sel.expressions[0]
        inner = proj.this if isinstance(proj, exp.Alias) else proj
        if inner.find(exp.AggFunc) or (isinstance(inner, exp.Anonymous) and _fname(inner) in (
                "collect_list", "collect_set", "to_json")):
            continue
        order = sel.args.get("order")
        if order is not None and order.expressions:
            first = order.expressions[0]
            fn = "max_by" if first.args.get("desc") else "min_by"
            wrapped = exp.func(fn, inner.copy(), first.this.copy())
            sel.set("order", None)
            sel.set("limit", None)
        else:
            wrapped = exp.func("any_value", inner.copy())
        new = exp.alias_(wrapped, proj.alias) if isinstance(proj, exp.Alias) else wrapped
        sel.set("expressions", [new])


def _inside_aggregate(node: exp.Expression) -> bool:
    p = node.parent
    while p is not None:
        if _fname(p) in ("collect_list", "collect_set", "to_json"):
            return True
        p = p.parent
    return False


# ---------------------------------------------------------------------------
# Binding parameters as literals
# ---------------------------------------------------------------------------
def literal(value) -> exp.Expression:
    if value is None:
        return exp.Null()
    if isinstance(value, bool):
        return exp.Boolean(this=value)
    if isinstance(value, (int, float, Decimal)):
        if isinstance(value, float) and value != value:  # NaN
            return exp.Null()
        return exp.Literal.number(format(value, "f") if isinstance(value, Decimal) else repr(value)
                                  if isinstance(value, float) else str(value))
    if isinstance(value, datetime):
        return exp.cast(exp.Literal.string(value.isoformat(sep=" ")), "TIMESTAMP")
    if isinstance(value, date):
        return exp.cast(exp.Literal.string(value.isoformat()), "DATE")
    if isinstance(value, (list, tuple, set)):
        items = list(value)
        return exp.Array(expressions=[literal(v) for v in items])
    if isinstance(value, dict):
        return exp.Literal.string(json.dumps(value, default=str))
    return exp.Literal.string(str(value))


def bind(tree: exp.Expression, args: tuple) -> exp.Expression:
    def sub(node):
        if isinstance(node, exp.Placeholder) and node.name and node.name.startswith("p"):
            idx = int(node.name[1:]) - 1
            if idx >= len(args):
                raise TranslationError(f"missing argument ${idx + 1}")
            return literal(args[idx])
        return node
    return tree.copy().transform(sub)


def render(tree: exp.Expression) -> str:
    return tree.sql(dialect="databricks")


# ---------------------------------------------------------------------------
# Plans
# ---------------------------------------------------------------------------
@dataclass
class Prepared:
    kind: str                       # select | insert | merge | update | delete | other
    tree: exp.Expression            # dialect-fixed statement (placeholders unbound)
    table: str | None = None
    returning: list[exp.Expression] | None = None
    # insert / merge
    columns: list[str] = field(default_factory=list)
    rows: list[list[exp.Expression]] | None = None   # VALUES rows (None = INSERT … SELECT)
    source_select: exp.Expression | None = None
    conflict_keys: list[list[str]] = field(default_factory=list)
    do_nothing: bool = False
    update_set: list[tuple[str, exp.Expression]] = field(default_factory=list)
    update_where: exp.Expression | None = None
    # update / delete
    where: exp.Expression | None = None


def _table_name(node: exp.Expression) -> str:
    t = node.find(exp.Table) if not isinstance(node, exp.Table) else node
    return t.name


@lru_cache(maxsize=4096)
def prepare(sql: str) -> Prepared:
    tree = _fix_dialect(_parse(sql))
    if isinstance(tree, (exp.Select, exp.Union, exp.Except, exp.Intersect)) or (
            isinstance(tree, exp.With) or tree.find(exp.Select) is tree):
        return Prepared("select", tree)
    if isinstance(tree, exp.Insert):
        return _prepare_insert(tree)
    if isinstance(tree, exp.Update):
        return Prepared("update", tree, table=_table_name(tree.this),
                        returning=_returning(tree), where=tree.args.get("where"))
    if isinstance(tree, exp.Delete):
        return Prepared("delete", tree, table=_table_name(tree.this),
                        returning=_returning(tree), where=tree.args.get("where"))
    return Prepared("other", tree)


def _returning(tree: exp.Expression) -> list[exp.Expression] | None:
    ret = tree.args.get("returning")
    if ret is None:
        return None
    tree.set("returning", None)
    return list(ret.expressions)


def _prepare_insert(tree: exp.Insert) -> Prepared:
    target = tree.this
    if isinstance(target, exp.Schema):
        table = target.this.name
        columns = [c.name for c in target.expressions]
    else:
        table = target.name
        columns = [c["name"] for c in table_meta(table)["columns"]]
    returning = _returning(tree)
    expr = tree.expression
    rows = None
    source_select = None
    if isinstance(expr, exp.Values):
        rows = [list(t.expressions) for t in expr.expressions]
    else:
        source_select = expr
    conflict = tree.args.get("conflict")
    p = Prepared("insert", tree, table=table, returning=returning, columns=columns,
                 rows=rows, source_select=source_select)
    if conflict is None:
        return p
    p.kind = "merge"
    meta = table_meta(table)
    keys = [c.name for c in (conflict.args.get("conflict_keys") or [])]
    if keys:
        p.conflict_keys = [keys]
    else:  # no target: any unique key conflicts
        p.conflict_keys = [k for k in [meta["primary_key"], *meta["unique"]] if k]
    action = conflict.args.get("action")
    p.do_nothing = bool(conflict.args.get("duplicate") is None and (
        action is None or "NOTHING" in str(action).upper()))
    for eq in conflict.args.get("expressions") or []:
        p.update_set.append((eq.this.name, eq.expression))
    if p.update_set:
        p.do_nothing = False
    where = conflict.args.get("where")
    p.update_where = where.this if isinstance(where, exp.Where) else where
    return p


# ---------------------------------------------------------------------------
# Statement builders (called by the backend with bound values)
# ---------------------------------------------------------------------------
def requalify(expr: exp.Expression, table: str, alias: str, excluded_alias: str | None = None) -> exp.Expression:
    """Point column refs at a MERGE alias: EXCLUDED.x -> s.x, table.x / x -> t.x."""
    def fix(node):
        if isinstance(node, exp.Column):
            q = node.table
            if excluded_alias and q.lower() == "excluded":
                return exp.column(node.name, excluded_alias)
            if not q or q == table:
                return exp.column(node.name, alias)
        return node
    return expr.copy().transform(fix)


def default_expr(col: dict) -> exp.Expression:
    d = col.get("default")
    if d is None:
        return exp.Null()
    return sqlglot.parse_one(d, read="databricks")


def merge_sql(table: str, columns: list[str], source_sql: str, keys: list[list[str]],
              update_set: list[tuple[str, exp.Expression]], update_where: exp.Expression | None,
              do_nothing: bool) -> str:
    meta = table_meta(table)
    on = " OR ".join("(" + " AND ".join(f"t.{k} = s.{k}" for k in ks) + ")" for ks in keys)
    parts = [f"MERGE INTO {table} AS t USING ({source_sql}) AS s ON {on}"]
    if not do_nothing and update_set:
        sets = ", ".join(
            f"t.{c} = {render(requalify(v, table, 't', 's'))}" for c, v in update_set)
        cond = f" AND {render(requalify(update_where, table, 't', 's'))}" if update_where is not None else ""
        parts.append(f"WHEN MATCHED{cond} THEN UPDATE SET {sets}")
    # Columns the INSERT didn't name get their declared default (Delta would too,
    # but being explicit keeps NOT NULL defaults working on every runtime).
    named = set(columns)
    extra = [c for c in meta["columns"] if c["name"] not in named and c.get("default") is not None]
    ins_cols = columns + [c["name"] for c in extra]
    ins_vals = [f"s.{c}" for c in columns] + [render(default_expr(c)) for c in extra]
    parts.append(f"WHEN NOT MATCHED THEN INSERT ({', '.join(ins_cols)}) VALUES ({', '.join(ins_vals)})")
    return " ".join(parts)


def values_source(columns: list[str], rows: list[list[str]]) -> str:
    """A SELECT … UNION ALL SELECT … source with named columns."""
    selects = ["SELECT " + ", ".join(f"{v} AS {c}" for c, v in zip(columns, row)) for row in rows]
    return " UNION ALL ".join(selects)


def cascade_statements(table: str, where_sql: str | None, depth: int = 0) -> list[str]:
    """Child DELETE/UPDATE statements emulating ON DELETE CASCADE / SET NULL, deepest
    first, for `DELETE FROM table WHERE where_sql`."""
    if depth > 6:
        raise TranslationError("foreign-key cascade too deep")
    out: list[str] = []
    pk_cols = table_meta(table)["primary_key"]
    for child, cmeta in schema_meta().items():
        for fk in cmeta["foreign_keys"]:
            if fk["ref_table"] != table or fk["on_delete"] not in ("cascade", "set_null"):
                continue
            ref = fk["ref_column"]
            parent_keys = f"SELECT {ref} FROM {table}" + (f" WHERE {where_sql}" if where_sql else "")
            cond = f"{fk['column']} IN ({parent_keys})"
            if fk["on_delete"] == "cascade":
                if child != table:
                    out += cascade_statements(child, cond, depth + 1)
                    out.append(f"DELETE FROM {child} WHERE {cond}")
            else:
                out.append(f"UPDATE {child} SET {fk['column']} = NULL WHERE {cond}")
    del pk_cols
    return out
